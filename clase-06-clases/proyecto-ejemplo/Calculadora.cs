// Solo agrupa miembros estáticos. Se accede por el nombre de la clase.

public static class Calculadora
{
    public static int Sumar(int a, int b)
    {
        return a + b;
    }

    public static int Restar(int a, int b)
    {
        return a - b;
    }
}
